/**
 * Progressive-web-app pieces: the manifest, the <head> tags every page needs, and a service
 * worker that precaches the whole book so it reads offline once installed or first visited.
 *
 * Every URL is relative, so the book works at a domain root or under a subpath (a GitHub Pages
 * project site, say). The cache name carries a hash of the built content, so any rebuild
 * invalidates the previous cache on the next visit.
 */

